-- 11_ai_assistant_schema.sql
-- Oracle 19c/21c/23c DDL migration for NEXA AI Conversation and Message Storage
-- Safe to run repeatedly: existing tables and indexes are left unchanged.

SET SERVEROUTPUT ON;

DECLARE
  PROCEDURE create_if_missing(p_ddl VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE = -955 THEN
        DBMS_OUTPUT.PUT_LINE('Object already exists; skipped.');
      ELSE
        RAISE;
      END IF;
  END;
BEGIN
  -- 1. AI_CONVERSATIONS Table
  create_if_missing(q'[
    CREATE TABLE AI_CONVERSATIONS (
      CONVERSATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      USER_ID         NUMBER NOT NULL,
      TITLE           VARCHAR2(120) NOT NULL,
      CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_AI_CONVERSATIONS PRIMARY KEY (CONVERSATION_ID),
      CONSTRAINT FK_AI_CONVERSATIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_AI_CONV_TITLE_LEN CHECK (LENGTH(TRIM(TITLE)) BETWEEN 1 AND 120)
    )]');

  create_if_missing('CREATE INDEX IDX_AI_CONV_USER ON AI_CONVERSATIONS (USER_ID, UPDATED_AT DESC)');

  -- 2. AI_MESSAGES Table
  create_if_missing(q'[
    CREATE TABLE AI_MESSAGES (
      MESSAGE_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      CONVERSATION_ID NUMBER NOT NULL,
      ROLE            VARCHAR2(20) NOT NULL,
      CONTENT         VARCHAR2(4000) NOT NULL,
      CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_AI_MESSAGES PRIMARY KEY (MESSAGE_ID),
      CONSTRAINT FK_AI_MESSAGES_CONV FOREIGN KEY (CONVERSATION_ID) REFERENCES AI_CONVERSATIONS(CONVERSATION_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_AI_MSG_ROLE CHECK (ROLE IN ('system', 'user', 'assistant')),
      CONSTRAINT CHK_AI_MSG_CONTENT_LEN CHECK (LENGTH(TRIM(CONTENT)) >= 1)
    )]');

  create_if_missing('CREATE INDEX IDX_AI_MSG_CONV ON AI_MESSAGES (CONVERSATION_ID, CREATED_AT ASC)');
END;
/
