-- Adds Oracle persistence required by group chat and broadcast messaging.
-- Safe to run repeatedly: existing tables and indexes are left unchanged.

SET SERVEROUTPUT ON;

DECLARE
  PROCEDURE create_if_missing(p_ddl VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE = -955 THEN
        DBMS_OUTPUT.PUT_LINE('Object already exists; skipped.');
      ELSE
        RAISE;
      END IF;
  END;
BEGIN
  create_if_missing(q'[
    CREATE TABLE GROUPS (
      GROUP_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      NAME VARCHAR2(100) NOT NULL,
      DESCRIPTION VARCHAR2(500),
      CREATED_BY NUMBER NOT NULL,
      AVATAR_URL VARCHAR2(1000),
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_GROUPS PRIMARY KEY (GROUP_ID),
      CONSTRAINT FK_GROUPS_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_GROUPS_NAME CHECK (LENGTH(TRIM(NAME)) BETWEEN 1 AND 100)
    )]');

  create_if_missing(q'[
    CREATE TABLE GROUP_MEMBERS (
      GROUP_ID NUMBER NOT NULL,
      USER_ID NUMBER NOT NULL,
      ROLE VARCHAR2(10) DEFAULT 'MEMBER' NOT NULL,
      JOINED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_GROUP_MEMBERS PRIMARY KEY (GROUP_ID, USER_ID),
      CONSTRAINT FK_GROUP_MEMBERS_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(GROUP_ID) ON DELETE CASCADE,
      CONSTRAINT FK_GROUP_MEMBERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_GROUP_MEMBER_ROLE CHECK (ROLE IN ('ADMIN', 'MEMBER'))
    )]');

  create_if_missing(q'[
    CREATE TABLE GROUP_MESSAGES (
      MESSAGE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      GROUP_ID NUMBER NOT NULL,
      SENDER_ID NUMBER NOT NULL,
      CONTENT VARCHAR2(4000) NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_GROUP_MESSAGES PRIMARY KEY (MESSAGE_ID),
      CONSTRAINT FK_GROUP_MESSAGES_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(GROUP_ID) ON DELETE CASCADE,
      CONSTRAINT FK_GROUP_MESSAGES_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_GROUP_MESSAGE_CONTENT CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 4000)
    )]');

  create_if_missing(q'[
    CREATE TABLE BROADCASTS (
      BROADCAST_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      SENDER_ID NUMBER NOT NULL,
      TITLE VARCHAR2(200) NOT NULL,
      CONTENT VARCHAR2(4000) NOT NULL,
      RECIPIENTS_COUNT NUMBER DEFAULT 0 NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_BROADCASTS PRIMARY KEY (BROADCAST_ID),
      CONSTRAINT FK_BROADCASTS_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_BROADCAST_CONTENT CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 4000),
      CONSTRAINT CHK_BROADCAST_RECIPIENTS CHECK (RECIPIENTS_COUNT >= 0)
    )]');

  create_if_missing(q'[
    CREATE TABLE BROADCAST_RECIPIENTS (
      BROADCAST_ID NUMBER NOT NULL,
      RECIPIENT_USER_ID NUMBER NOT NULL,
      CONSTRAINT PK_BROADCAST_RECIPIENTS PRIMARY KEY (BROADCAST_ID, RECIPIENT_USER_ID),
      CONSTRAINT FK_BROADCAST_RECIPIENTS_BROADCAST FOREIGN KEY (BROADCAST_ID) REFERENCES BROADCASTS(BROADCAST_ID) ON DELETE CASCADE,
      CONSTRAINT FK_BROADCAST_RECIPIENTS_USER FOREIGN KEY (RECIPIENT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
    )]');

  create_if_missing('CREATE INDEX IDX_GROUP_MEMBERS_USER ON GROUP_MEMBERS (USER_ID, GROUP_ID)');
  create_if_missing('CREATE INDEX IDX_GROUP_MESSAGES_GROUP ON GROUP_MESSAGES (GROUP_ID, CREATED_AT)');
  create_if_missing('CREATE INDEX IDX_BROADCASTS_SENDER ON BROADCASTS (SENDER_ID, CREATED_AT DESC)');
  create_if_missing('CREATE INDEX IDX_BROADCAST_RECIPIENT_USER ON BROADCAST_RECIPIENTS (RECIPIENT_USER_ID, BROADCAST_ID)');
END;
/

PROMPT Group and broadcast Oracle migration completed.
