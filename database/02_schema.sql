-- Complete Oracle 19c/21c XE / 23c Free DDL Schema Definition for Nexa Social Platform

SET SERVEROUTPUT ON;

-- 1. USERS TABLE
CREATE TABLE USERS (
  USER_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USERNAME          VARCHAR2(30) NOT NULL,
  EMAIL             VARCHAR2(255) NOT NULL,
  PASSWORD_HASH     VARCHAR2(255) NOT NULL,
  DISPLAY_NAME      VARCHAR2(60) NOT NULL,
  BIO               VARCHAR2(500),
  PROFILE_IMAGE_URL VARCHAR2(1000),
  COVER_IMAGE_URL   VARCHAR2(1000),
  LOCATION          VARCHAR2(100),
  WEBSITE_URL       VARCHAR2(500),
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
  CONSTRAINT UQ_USERS_USERNAME UNIQUE (USERNAME),
  CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CHK_USERS_USERNAME_LEN CHECK (LENGTH(USERNAME) >= 3),
  CONSTRAINT CHK_USERS_DISPLAY_LEN CHECK (LENGTH(DISPLAY_NAME) >= 2)
);

CREATE INDEX IDX_USERS_USERNAME_LOWER ON USERS (LOWER(USERNAME));
CREATE INDEX IDX_USERS_EMAIL_LOWER ON USERS (LOWER(EMAIL));
CREATE INDEX IDX_USERS_DISPLAY_NAME ON USERS (DISPLAY_NAME);

-- 2. POSTS TABLE
CREATE TABLE POSTS (
  POST_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_ID           NUMBER NOT NULL,
  CONTENT           VARCHAR2(2000),
  IMAGE_URL         VARCHAR2(1000),
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_POSTS PRIMARY KEY (POST_ID),
  CONSTRAINT FK_POSTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_POSTS_NON_EMPTY CHECK (CONTENT IS NOT NULL OR IMAGE_URL IS NOT NULL)
);

CREATE INDEX IDX_POSTS_FEED ON POSTS (CREATED_AT DESC, POST_ID DESC);
CREATE INDEX IDX_POSTS_USER ON POSTS (USER_ID, CREATED_AT DESC);

-- 3. COMMENTS TABLE
CREATE TABLE COMMENTS (
  COMMENT_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  POST_ID           NUMBER NOT NULL,
  USER_ID           NUMBER NOT NULL,
  CONTENT           VARCHAR2(1000) NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_COMMENTS PRIMARY KEY (COMMENT_ID),
  CONSTRAINT FK_COMMENTS_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID) ON DELETE CASCADE,
  CONSTRAINT FK_COMMENTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_COMMENTS_LEN CHECK (LENGTH(TRIM(CONTENT)) >= 1)
);

CREATE INDEX IDX_COMMENTS_POST ON COMMENTS (POST_ID, CREATED_AT ASC);

-- 4. LIKES TABLE (COMPOSITE KEY)
CREATE TABLE LIKES (
  POST_ID           NUMBER NOT NULL,
  USER_ID           NUMBER NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_LIKES PRIMARY KEY (POST_ID, USER_ID),
  CONSTRAINT FK_LIKES_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID) ON DELETE CASCADE,
  CONSTRAINT FK_LIKES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_LIKES_USER ON LIKES (USER_ID);

-- 5. FOLLOWERS TABLE (COMPOSITE KEY & SELF-FOLLOW CHECK)
CREATE TABLE FOLLOWERS (
  FOLLOWER_ID       NUMBER NOT NULL,
  FOLLOWING_ID      NUMBER NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_FOLLOWERS PRIMARY KEY (FOLLOWER_ID, FOLLOWING_ID),
  CONSTRAINT FK_FOLLOWERS_FOLLOWER FOREIGN KEY (FOLLOWER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_FOLLOWERS_FOLLOWING FOREIGN KEY (FOLLOWING_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_NO_SELF_FOLLOW CHECK (FOLLOWER_ID <> FOLLOWING_ID)
);

CREATE INDEX IDX_FOLLOWERS_FOLLOWING ON FOLLOWERS (FOLLOWING_ID);

-- 6. REFRESH_TOKENS TABLE
CREATE TABLE REFRESH_TOKENS (
  TOKEN_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_ID           NUMBER NOT NULL,
  TOKEN_HASH        VARCHAR2(255) NOT NULL,
  EXPIRES_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
  REVOKED_AT        TIMESTAMP WITH TIME ZONE,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_REFRESH_TOKENS PRIMARY KEY (TOKEN_ID),
  CONSTRAINT FK_TOKENS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_REFRESH_TOKENS_HASH ON REFRESH_TOKENS (TOKEN_HASH);

-- 7. BOOKMARKS TABLE (COMPOSITE KEY)
CREATE TABLE BOOKMARKS (
  USER_ID           NUMBER NOT NULL,
  POST_ID           NUMBER NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_BOOKMARKS PRIMARY KEY (USER_ID, POST_ID),
  CONSTRAINT FK_BOOKMARKS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_BOOKMARKS_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID) ON DELETE CASCADE
);

-- 8. NOTIFICATIONS TABLE
CREATE TABLE NOTIFICATIONS (
  NOTIFICATION_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  RECIPIENT_USER_ID  NUMBER NOT NULL,
  ACTOR_USER_ID     NUMBER NOT NULL,
  TYPE              VARCHAR2(30) NOT NULL,
  POST_ID           NUMBER,
  IS_READ           NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (NOTIFICATION_ID),
  CONSTRAINT FK_NOTIF_RECIPIENT FOREIGN KEY (RECIPIENT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_NOTIF_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_NOTIF_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_NOTIF_IS_READ CHECK (IS_READ IN (0, 1)),
  CONSTRAINT CHK_NOTIF_TYPE CHECK (TYPE IN ('LIKE', 'COMMENT', 'FOLLOW'))
);

CREATE INDEX IDX_NOTIF_RECIPIENT ON NOTIFICATIONS (RECIPIENT_USER_ID, CREATED_AT DESC);

-- 9. DIRECT MESSAGES
CREATE TABLE MESSAGES (
  MESSAGE_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  SENDER_ID         NUMBER NOT NULL,
  RECEIVER_ID       NUMBER NOT NULL,
  CONTENT           VARCHAR2(4000) NOT NULL,
  READ_AT           TIMESTAMP WITH TIME ZONE,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MESSAGES PRIMARY KEY (MESSAGE_ID),
  CONSTRAINT FK_MESSAGES_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT FK_MESSAGES_RECEIVER FOREIGN KEY (RECEIVER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_MESSAGES_PARTICIPANTS CHECK (SENDER_ID <> RECEIVER_ID),
  CONSTRAINT CHK_MESSAGES_CONTENT CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 4000)
);

CREATE INDEX IDX_MESSAGES_CONVERSATION ON MESSAGES (SENDER_ID, RECEIVER_ID, MESSAGE_ID);
CREATE INDEX IDX_MESSAGES_RECEIVER_UNREAD ON MESSAGES (RECEIVER_ID, READ_AT, MESSAGE_ID);

-- 10. 24-HOUR STORIES
CREATE TABLE STORIES (
  STORY_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_ID           NUMBER NOT NULL,
  MEDIA_URL         VARCHAR2(1000) NOT NULL,
  CAPTION           VARCHAR2(1000),
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  EXPIRES_AT        TIMESTAMP WITH TIME ZONE DEFAULT (SYSTIMESTAMP + INTERVAL '24' HOUR) NOT NULL,
  CONSTRAINT PK_STORIES PRIMARY KEY (STORY_ID),
  CONSTRAINT FK_STORIES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_STORIES_EXPIRY CHECK (EXPIRES_AT > CREATED_AT)
);

CREATE INDEX IDX_STORIES_ACTIVE ON STORIES (EXPIRES_AT, CREATED_AT DESC);
CREATE INDEX IDX_STORIES_USER ON STORIES (USER_ID, CREATED_AT DESC);

-- 11. REELS AND REEL LIKES
CREATE TABLE REELS (
  REEL_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_ID           NUMBER NOT NULL,
  VIDEO_URL         VARCHAR2(1000) NOT NULL,
  CAPTION           VARCHAR2(1000),
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_REELS PRIMARY KEY (REEL_ID),
  CONSTRAINT FK_REELS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE TABLE REEL_LIKES (
  REEL_ID           NUMBER NOT NULL,
  USER_ID           NUMBER NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_REEL_LIKES PRIMARY KEY (REEL_ID, USER_ID),
  CONSTRAINT FK_REEL_LIKES_REEL FOREIGN KEY (REEL_ID) REFERENCES REELS(REEL_ID) ON DELETE CASCADE,
  CONSTRAINT FK_REEL_LIKES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_REELS_FEED ON REELS (CREATED_AT DESC, REEL_ID DESC);
CREATE INDEX IDX_REEL_LIKES_USER ON REEL_LIKES (USER_ID, CREATED_AT DESC);

-- 12. DURABLE MEDIA METADATA (file bytes live in configured storage)
CREATE TABLE MEDIA_ASSETS (
  ASSET_ID          VARCHAR2(36),
  USER_ID           NUMBER NOT NULL,
  STORAGE_KEY       VARCHAR2(255) NOT NULL,
  ORIGINAL_NAME     VARCHAR2(255) NOT NULL,
  MIME_TYPE         VARCHAR2(100) NOT NULL,
  SIZE_BYTES        NUMBER NOT NULL,
  MEDIA_KIND        VARCHAR2(20) NOT NULL,
  CREATED_AT        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MEDIA_ASSETS PRIMARY KEY (ASSET_ID),
  CONSTRAINT UQ_MEDIA_STORAGE_KEY UNIQUE (STORAGE_KEY),
  CONSTRAINT FK_MEDIA_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_MEDIA_SIZE CHECK (SIZE_BYTES > 0),
  CONSTRAINT CHK_MEDIA_KIND CHECK (MEDIA_KIND IN ('AVATAR', 'PHOTO', 'STORY', 'REEL', 'CHAT'))
);

CREATE INDEX IDX_MEDIA_USER_CREATED ON MEDIA_ASSETS (USER_ID, CREATED_AT DESC);

-- 13. GROUP CHAT
CREATE TABLE GROUPS (
  GROUP_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NAME               VARCHAR2(100) NOT NULL,
  DESCRIPTION        VARCHAR2(500),
  CREATED_BY         NUMBER NOT NULL,
  AVATAR_URL         VARCHAR2(1000),
  CREATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GROUPS PRIMARY KEY (GROUP_ID),
  CONSTRAINT FK_GROUPS_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_GROUPS_NAME CHECK (LENGTH(TRIM(NAME)) BETWEEN 1 AND 100)
);

CREATE TABLE GROUP_MEMBERS (
  GROUP_ID           NUMBER NOT NULL,
  USER_ID            NUMBER NOT NULL,
  ROLE               VARCHAR2(10) DEFAULT 'MEMBER' NOT NULL,
  JOINED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GROUP_MEMBERS PRIMARY KEY (GROUP_ID, USER_ID),
  CONSTRAINT FK_GROUP_MEMBERS_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(GROUP_ID) ON DELETE CASCADE,
  CONSTRAINT FK_GROUP_MEMBERS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_GROUP_MEMBER_ROLE CHECK (ROLE IN ('ADMIN', 'MEMBER'))
);

CREATE TABLE GROUP_MESSAGES (
  MESSAGE_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  GROUP_ID           NUMBER NOT NULL,
  SENDER_ID          NUMBER NOT NULL,
  CONTENT            VARCHAR2(4000) NOT NULL,
  CREATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GROUP_MESSAGES PRIMARY KEY (MESSAGE_ID),
  CONSTRAINT FK_GROUP_MESSAGES_GROUP FOREIGN KEY (GROUP_ID) REFERENCES GROUPS(GROUP_ID) ON DELETE CASCADE,
  CONSTRAINT FK_GROUP_MESSAGES_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_GROUP_MESSAGE_CONTENT CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 4000)
);

CREATE INDEX IDX_GROUP_MEMBERS_USER ON GROUP_MEMBERS (USER_ID, GROUP_ID);
CREATE INDEX IDX_GROUP_MESSAGES_GROUP ON GROUP_MESSAGES (GROUP_ID, CREATED_AT);

-- 14. BROADCAST MESSAGING
CREATE TABLE BROADCASTS (
  BROADCAST_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  SENDER_ID          NUMBER NOT NULL,
  TITLE              VARCHAR2(200) NOT NULL,
  CONTENT            VARCHAR2(4000) NOT NULL,
  RECIPIENTS_COUNT   NUMBER DEFAULT 0 NOT NULL,
  CREATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_BROADCASTS PRIMARY KEY (BROADCAST_ID),
  CONSTRAINT FK_BROADCASTS_SENDER FOREIGN KEY (SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  CONSTRAINT CHK_BROADCAST_CONTENT CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 4000),
  CONSTRAINT CHK_BROADCAST_RECIPIENTS CHECK (RECIPIENTS_COUNT >= 0)
);

CREATE TABLE BROADCAST_RECIPIENTS (
  BROADCAST_ID       NUMBER NOT NULL,
  RECIPIENT_USER_ID  NUMBER NOT NULL,
  CONSTRAINT PK_BROADCAST_RECIPIENTS PRIMARY KEY (BROADCAST_ID, RECIPIENT_USER_ID),
  CONSTRAINT FK_BROADCAST_RECIPIENTS_BROADCAST FOREIGN KEY (BROADCAST_ID) REFERENCES BROADCASTS(BROADCAST_ID) ON DELETE CASCADE,
  CONSTRAINT FK_BROADCAST_RECIPIENTS_USER FOREIGN KEY (RECIPIENT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_BROADCASTS_SENDER ON BROADCASTS (SENDER_ID, CREATED_AT DESC);
CREATE INDEX IDX_BROADCAST_RECIPIENT_USER ON BROADCAST_RECIPIENTS (RECIPIENT_USER_ID, BROADCAST_ID);

