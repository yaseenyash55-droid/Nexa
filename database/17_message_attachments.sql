-- ====================================================================
-- NEXA ORACLE DATABASE SCHEMA MIGRATION
-- FILE: database/17_message_attachments.sql
-- DESCRIPTION: Add Unified Media and Music Attachments Schema
-- TARGETS: Oracle Database 19c/21c
-- ====================================================================

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE MESSAGE_ATTACHMENTS (
      ATTACHMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      MESSAGE_ID NUMBER REFERENCES MESSAGES(MESSAGE_ID) ON DELETE CASCADE,
      GROUP_MESSAGE_ID NUMBER REFERENCES GROUP_MESSAGES(MESSAGE_ID) ON DELETE CASCADE,
      BROADCAST_ID NUMBER REFERENCES BROADCASTS(BROADCAST_ID) ON DELETE CASCADE,
      
      ATTACHMENT_TYPE VARCHAR2(20) NOT NULL CHECK (ATTACHMENT_TYPE IN (''image'', ''video'', ''file'', ''music'', ''gif'')),
      
      -- Foreign Key for uploaded media (images, videos, files)
      MEDIA_ID VARCHAR2(36) REFERENCES MEDIA_ASSETS(ASSET_ID) ON DELETE SET NULL,
      
      -- Denormalized Metadata for Music/Jamendo to prevent playback failure if track is taken down
      MUSIC_PROVIDER VARCHAR2(30),
      MUSIC_TRACK_ID VARCHAR2(255),
      MUSIC_TITLE VARCHAR2(255),
      MUSIC_ARTIST VARCHAR2(255),
      MUSIC_ARTWORK_URL VARCHAR2(1000),
      MUSIC_AUDIO_URL VARCHAR2(1000),
      MUSIC_DURATION NUMBER,
      
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      
      CONSTRAINT CHK_ATTACH_DEST CHECK (
        (MESSAGE_ID IS NOT NULL AND GROUP_MESSAGE_ID IS NULL AND BROADCAST_ID IS NULL) OR
        (MESSAGE_ID IS NULL AND GROUP_MESSAGE_ID IS NOT NULL AND BROADCAST_ID IS NULL) OR
        (MESSAGE_ID IS NULL AND GROUP_MESSAGE_ID IS NULL AND BROADCAST_ID IS NOT NULL)
      )
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_MSG_ATT_MSG_ID ON MESSAGE_ATTACHMENTS (MESSAGE_ID)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 AND SQLCODE != -1408 THEN
      RAISE;
    END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_MSG_ATT_GROUP_MSG_ID ON MESSAGE_ATTACHMENTS (GROUP_MESSAGE_ID)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 AND SQLCODE != -1408 THEN
      RAISE;
    END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_MSG_ATT_BROADCAST_ID ON MESSAGE_ATTACHMENTS (BROADCAST_ID)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 AND SQLCODE != -1408 THEN
      RAISE;
    END IF;
END;
/
