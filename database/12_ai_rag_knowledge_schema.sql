-- 12_ai_rag_knowledge_schema.sql
-- NEXA Social Network: Oracle AI RAG Knowledge Base Schema
-- Stores approved platform documentation chunks and vector embeddings (stored as JSON array string for Oracle 19c/21c portability).

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE AI_KNOWLEDGE_DOCS (
      DOC_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      SOURCE VARCHAR2(100) NOT NULL,
      TITLE VARCHAR2(255) NOT NULL,
      CATEGORY VARCHAR2(100) DEFAULT ''general'' NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT UQ_AI_DOC_SOURCE UNIQUE (SOURCE)
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE '
    CREATE TABLE AI_KNOWLEDGE_CHUNKS (
      CHUNK_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      DOC_ID NUMBER NOT NULL,
      CHUNK_INDEX NUMBER NOT NULL,
      CONTENT CLOB NOT NULL,
      METADATA_JSON VARCHAR2(2000) DEFAULT ''{}'' NOT NULL,
      EMBEDDING_JSON CLOB NOT NULL,
      CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT FK_AI_CHUNK_DOC FOREIGN KEY (DOC_ID) REFERENCES AI_KNOWLEDGE_DOCS(DOC_ID) ON DELETE CASCADE,
      CONSTRAINT UQ_AI_CHUNK_INDEX UNIQUE (DOC_ID, CHUNK_INDEX)
    )
  ';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN
      RAISE;
    END IF;
END;
/

-- Indexes for performance
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_AI_CHUNK_DOC ON AI_KNOWLEDGE_CHUNKS(DOC_ID)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 AND SQLCODE != -1408 THEN
      RAISE;
    END IF;
END;
/
