-- 13_ai_memories_schema.sql
-- Oracle 19c/21c/23c DDL migration for User-Controlled NEXA AI Memory and Preferences
-- Safe to run repeatedly: existing tables and indexes are left unchanged.

SET SERVEROUTPUT ON;

DECLARE
  PROCEDURE create_if_missing(p_ddl VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE = -955 THEN
        DBMS_OUTPUT.PUT_LINE('Object already exists; skipped.');
      ELSE
        RAISE;
      END IF;
  END;
BEGIN
  -- 1. AI_PREFERENCES Table
  create_if_missing(q'[
    CREATE TABLE AI_PREFERENCES (
      USER_ID               NUMBER NOT NULL,
      PERSONALIZATION_ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
      PREFERRED_LANGUAGE    VARCHAR2(50) DEFAULT 'English',
      RESPONSE_LENGTH       VARCHAR2(20) DEFAULT 'balanced',
      WRITING_TONE          VARCHAR2(50) DEFAULT 'friendly',
      CREATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT            TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_AI_PREFERENCES PRIMARY KEY (USER_ID),
      CONSTRAINT FK_AI_PREFERENCES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_AI_PREF_ENABLED CHECK (PERSONALIZATION_ENABLED IN (0, 1)),
      CONSTRAINT CHK_AI_PREF_LENGTH CHECK (RESPONSE_LENGTH IN ('concise', 'balanced', 'detailed'))
    )]');

  -- 2. AI_MEMORIES Table
  create_if_missing(q'[
    CREATE TABLE AI_MEMORIES (
      MEMORY_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      USER_ID     NUMBER NOT NULL,
      KEY_NAME    VARCHAR2(80) NOT NULL,
      CONTENT     VARCHAR2(1000) NOT NULL,
      CATEGORY    VARCHAR2(50) DEFAULT 'general' NOT NULL,
      CREATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_AI_MEMORIES PRIMARY KEY (MEMORY_ID),
      CONSTRAINT FK_AI_MEMORIES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
      CONSTRAINT CHK_AI_MEM_KEY_LEN CHECK (LENGTH(TRIM(KEY_NAME)) BETWEEN 1 AND 80),
      CONSTRAINT CHK_AI_MEM_CONTENT_LEN CHECK (LENGTH(TRIM(CONTENT)) BETWEEN 1 AND 1000)
    )]');

  create_if_missing('CREATE INDEX IDX_AI_MEMORIES_USER ON AI_MEMORIES (USER_ID, CREATED_AT DESC)');
END;
/
